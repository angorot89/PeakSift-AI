"""Caption presets and positions, and the ASS document burned into a short.

Users choose a preset name and a position from fixed allow-lists; they never submit ASS
syntax, colours, fonts or sizes. Every Dialogue text goes through ``escape_ass_text`` so
transcript content stays inert. Coordinates assume the 1080 × 1920 canvas (``PlayRes``).
No animation, no per-word highlighting in V0.6.
"""

import math
import re
from collections.abc import Iterable
from dataclasses import dataclass

from app.services.clip_edit.captions import Cue, escape_ass_text
from app.services.clip_edit.config import (
    OUTPUT_HEIGHT,
    OUTPUT_WIDTH,
    CaptionPosition,
    CaptionStyle,
)

# Only plain family names reach the Style line (fields there are comma-separated).
_FONT_NAME = re.compile(r"^[A-Za-z0-9 _-]{1,64}$")


@dataclass(frozen=True)
class StylePreset:
    size: int
    bold: bool
    primary: str  # &HAABBGGRR
    outline_colour: str
    back_colour: str
    border_style: int  # 1 = outline + shadow, 3 = opaque box (drawn in the outline colour)
    outline: float
    shadow: float


PRESETS: dict[CaptionStyle, StylePreset] = {
    # Understated white text with a thin outline.
    CaptionStyle.CLEAN: StylePreset(
        size=62,
        bold=False,
        primary="&H00FFFFFF",
        outline_colour="&H00000000",
        back_colour="&H80000000",
        border_style=1,
        outline=3,
        shadow=1,
    ),
    # Large heavy white text with a thick black outline: readable over busy footage.
    CaptionStyle.BOLD: StylePreset(
        size=80,
        bold=True,
        primary="&H00FFFFFF",
        outline_colour="&H00000000",
        back_colour="&H80000000",
        border_style=1,
        outline=6,
        shadow=2,
    ),
    # Yellow text on a dark translucent box, the familiar creator look.
    CaptionStyle.CREATOR: StylePreset(
        size=72,
        bold=True,
        primary="&H004DE1FF",
        outline_colour="&H33000000",
        back_colour="&H00000000",
        border_style=3,
        outline=18,
        shadow=0,
    ),
}

SIDE_MARGIN = 90
# Bottom/top captions stay clear of the edges and of platform UI overlays.
POSITIONS: dict[CaptionPosition, tuple[int, int]] = {
    # position: (ASS numpad alignment, vertical margin)
    CaptionPosition.BOTTOM: (2, 320),
    CaptionPosition.CENTER: (5, 0),
    CaptionPosition.TOP: (8, 260),
}

STYLE_FORMAT = (
    "Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, "
    "BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, "
    "BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding"
)
EVENT_FORMAT = "Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text"


def ass_time(seconds: float) -> str:
    """``H:MM:SS.cc`` (centiseconds), never negative."""
    centis = max(0, int(round(seconds * 100)))
    hours, rest = divmod(centis, 360_000)
    minutes, rest = divmod(rest, 6_000)
    secs, cs = divmod(rest, 100)
    return f"{hours}:{minutes:02d}:{secs:02d}.{cs:02d}"


def build_ass_document(
    cues: Iterable[Cue],
    *,
    style: CaptionStyle,
    position: CaptionPosition,
    font_family: str,
    extra_styles: Iterable[str] = (),
    extra_events: Iterable[str] = (),
) -> str:
    if not _FONT_NAME.fullmatch(font_family):
        raise ValueError("Unsupported caption font family name")
    preset = PRESETS[style]
    alignment, margin_v = POSITIONS[position]
    style_line = (
        f"Style: Caption,{font_family},{preset.size},{preset.primary},{preset.primary},"
        f"{preset.outline_colour},{preset.back_colour},{-1 if preset.bold else 0},0,0,0,"
        f"100,100,0,0,{preset.border_style},{preset.outline:g},{preset.shadow:g},"
        f"{alignment},{SIDE_MARGIN},{SIDE_MARGIN},{margin_v},1"
    )
    lines = [
        "[Script Info]",
        "; Generated by PeakSift from the transcript. Text is escaped; no user markup.",
        "ScriptType: v4.00+",
        f"PlayResX: {OUTPUT_WIDTH}",
        f"PlayResY: {OUTPUT_HEIGHT}",
        "WrapStyle: 0",
        "ScaledBorderAndShadow: yes",
        "YCbCr Matrix: TV.709",
        "",
        "[V4+ Styles]",
        STYLE_FORMAT,
        style_line,
        *extra_styles,
        "",
        "[Events]",
        EVENT_FORMAT,
    ]
    for cue in cues:
        if not (math.isfinite(cue.start) and math.isfinite(cue.end)) or cue.end <= cue.start:
            continue
        start, end = ass_time(cue.start), ass_time(cue.end)
        if end <= start:  # rounding to centiseconds must not produce an empty cue
            end = ass_time(cue.start + 0.01)
        lines.append(f"Dialogue: 0,{start},{end},Caption,,0,0,0,,{escape_ass_text(cue.text)}")
    lines.extend(extra_events)
    return "\n".join(lines) + "\n"
